NAMES = tuple(_PATHS)


def svg(name: str, color: str, size: int = 24) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24" '
        f'fill="none" stroke="{color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">'
        f"{_PATHS[name]}</svg>"
    )


def _dpr() -> float:
    app = QGuiApplication.instance()
    return app.devicePixelRatio() if app else 1.0


@lru_cache(maxsize=512)
def _pixmap(name: str, color: str, size: int, dpr: float) -> QPixmap:
    renderer = QSvgRenderer(QByteArray(svg(name, color).encode()))
    pm = QPixmap(round(size * dpr), round(size * dpr))
    pm.fill(Qt.GlobalColor.transparent)
    painter = QPainter(pm)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(painter, QRectF(0, 0, pm.width(), pm.height()))
    painter.end()
    pm.setDevicePixelRatio(dpr)
    return pm


def pixmap(name: str, color: str, size: int) -> QPixmap:
    return _pixmap(name, color, size, _dpr())


def icon(name: str, color: str, size: int) -> QIcon:
    return QIcon(pixmap(name, color, size))


def svg_file(name: str, color: str, size: int) -> str:
    """Grava o ícone num arquivo temporário (para url() no QSS) e devolve o caminho."""
    pasta = Path(tempfile.gettempdir()) / "mesclador-icons"
    pasta.mkdir(exist_ok=True)
    arquivo = pasta / f"{name}-{color.lstrip('#').lower()}-{size}.svg"
    if not arquivo.exists():
        arquivo.write_text(svg(name, color, size), encoding="utf-8")
    return arquivo.as_posix()
